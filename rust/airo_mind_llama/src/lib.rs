// `deny`, not `forbid`. An FFI boundary is unsafe by construction -- the
// generated bridge dereferences pointers handed over by Dart -- and `forbid`
// cannot be lifted anywhere, including on generated code.
#![deny(unsafe_code)]
//! Airo Mind's generation half: llama.cpp and the bridge Flutter calls for it.
//!
//! # Why this is its own library
//!
//! See `airo_mind_whisper`'s root for the full account. Short version:
//! whisper.cpp and llama.cpp each statically vendor their own ggml, the trees
//! differ by 348 files, and a library containing both is a one-definition-rule
//! conflict that Android refuses outright and Apple "resolves" by picking a
//! definition per symbol. Two cdylibs keep each ggml private to its own image.
//!
//! # Loaded on demand
//!
//! This library is roughly 48 MB and only minutes need it. Dart does not load
//! it during startup or transcription; the first generation pays for it, behind
//! a visible state rather than a silent pause.

#[cfg(feature = "llama")]
pub mod api;

#[cfg(feature = "llama")]
#[allow(
    // The only unsafe in the crate. See the crate-level note above.
    unsafe_code,
    clippy::all,
    dead_code,
    unused_imports,
    non_snake_case,
    non_camel_case_types,
    missing_docs,
    clippy::needless_lifetimes
)]
// Generated by `flutter_rust_bridge_codegen`. Never edited by hand.
mod frb_generated;

#[cfg(feature = "llama")]
mod llama;

// `use`, not `mod`: `llama.rs` moved here from the old combined crate
// unchanged, so `crate::engine::…` and friends keep resolving. The definitions
